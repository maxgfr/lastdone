// Calendar export: one recurring all-day event per scheduled task, starting at its next due date.
// The schedule is recomputed from the last entry, so the file must be exported again after logging.
import { addDays, nextDue } from '../domain/schedule'
import type { LogEntry, Task } from '../domain/store'

const pad = (n: number) => String(n).padStart(2, '0')
const day = (date: Date) => `${date.getFullYear()}${pad(date.getMonth() + 1)}${pad(date.getDate())}`
const stamp = (date: Date) =>
  `${date.getUTCFullYear()}${pad(date.getUTCMonth() + 1)}${pad(date.getUTCDate())}T${pad(date.getUTCHours())}${pad(date.getUTCMinutes())}${pad(date.getUTCSeconds())}Z`

/** RFC 5545 text escaping. */
export function escapeText(text: string): string {
  return text.replace(/\\/g, '\\\\').replace(/;/g, '\\;').replace(/,/g, '\\,').replace(/\r?\n/g, '\\n')
}

/** Folds lines longer than 75 octets, as RFC 5545 requires. */
export function fold(line: string): string {
  const bytes = new TextEncoder().encode(line)
  if (bytes.length <= 75) return line
  const parts: string[] = []
  let current = ''
  let size = 0
  for (const char of line) {
    const length = new TextEncoder().encode(char).length
    if (size + length > (parts.length ? 74 : 75)) {
      parts.push(current)
      current = ''
      size = 0
    }
    current += char
    size += length
  }
  parts.push(current)
  return parts.join('\r\n ')
}

export function buildIcs(tasks: Task[], log: LogEntry[], now = new Date()): string {
  const lines = ['BEGIN:VCALENDAR', 'VERSION:2.0', 'PRODID:-//lastdone//EN', 'CALSCALE:GREGORIAN', 'X-WR-CALNAME:lastdone']
  for (const task of tasks) {
    const due = nextDue(task, log, now)
    if (!due || !task.intervalDays) continue
    // An overdue task starts today rather than in the past.
    const start = due < now ? now : due
    lines.push(
      'BEGIN:VEVENT',
      `UID:${task.id}@lastdone`,
      `DTSTAMP:${stamp(now)}`,
      `DTSTART;VALUE=DATE:${day(start)}`,
      `DTEND;VALUE=DATE:${day(addDays(start, 1))}`,
      `RRULE:FREQ=DAILY;INTERVAL=${task.intervalDays}`,
      `SUMMARY:${escapeText(task.name)}`,
      `DESCRIPTION:${escapeText(`Every ${task.intervalDays} days. Generated by lastdone; export again after logging to shift the dates.`)}`,
      'BEGIN:VALARM',
      'ACTION:DISPLAY',
      `DESCRIPTION:${escapeText(task.name)}`,
      'TRIGGER:PT9H',
      'END:VALARM',
      'END:VEVENT',
    )
  }
  lines.push('END:VCALENDAR')
  return `${lines.map(fold).join('\r\n')}\r\n`
}
